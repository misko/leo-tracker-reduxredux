def owned_read(adapter, frame, raw, *, expected_eof=True):
    source = np.frombuffer(frame, dtype=np.uint8)
    window = len(raw) // 2
    context = adapter.fused_history_open_unindexed(source.ctypes.data, len(frame), len(raw), window)
    assert context is not None and context.native
    outputs = []
    try:
        capacity = adapter.fused_history_owned_capacity(context)
        for _ in range(2):
            output = np.empty(capacity, dtype=np.uint8)
            assert adapter.fused_history_read_owned(context, output.ctypes.data, capacity)
            outputs.append(output)
        assert b"".join(output[:window].tobytes() for output in outputs) == raw
        assert bool(adapter.fused_history_finish(context)) is expected_eof
        return adapter.finished
    finally:
        adapter.fused_history_close(context)


def test_owned_history_crosses_window_with_one_bounded_seam(decoder, ordinary_ports, owned_frame):
    frame, raw = owned_frame
    receipt = owned_read(OwnedPorts(decoder, ordinary_ports), frame, raw)
    assert (receipt["route"], receipt["mixed_blocks"], receipt["emitted"]) == ("paired", 1, 2)
    assert (receipt["history_bytes"], receipt["seam_copy_bytes"], receipt["spill_bytes"]) == (131072, 262144, 0)


def test_owned_runtime_replay_skips_already_delivered_window(decoder, ordinary_ports, owned_frame, monkeypatch):
    original = decoder.owned_read
    issued = []

    def fail_second(*args):
        issued.append(args)
        return original(*args) if len(issued) == 1 else 0

    monkeypatch.setattr(decoder, "owned_read", fail_second)
    report = owned_read(OwnedPorts(decoder, ordinary_ports), *owned_frame)
    assert report["route"] == "ordinary_fallback" and report["emitted"] == 2 and report["replayed"] == 1


