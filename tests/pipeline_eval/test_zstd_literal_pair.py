import ctypes as ct
from dataclasses import replace

import numpy as np
import pytest
import zstandard as zstd

from reports.ALGO08.v3 import zstd_literal_pair as pair


@pytest.fixture(scope="module")
def decoder(tmp_path_factory):
    shared = tmp_path_factory.mktemp("zstd-literal-pairs") / "pair.so"
    return pair.Decoder(shared, pair.build(shared))


def authority(frame, raw):
    windows = tuple((len(w), pair.digest(w)) for w in (raw[:31227], raw[31227:]))
    return pair.Authority(len(frame), pair.digest(frame), len(raw), pair.digest(raw), windows)


def with_literals(raw, sequences=()):
    """Encode exact generated bytes with pinned producer and optional explicit blocks."""
    library = ct.CDLL(str(pair.SHARED))
    pointer, size = ct.c_void_p, ct.c_size_t
    library.ZSTD_createCCtx.restype = pointer
    library.ZSTD_freeCCtx.argtypes = (pointer,)
    library.ZSTD_CCtx_setParameter.argtypes = (pointer, ct.c_int, ct.c_int)
    library.ZSTD_CCtx_setParameter.restype = size
    library.ZSTD_compressSequences.argtypes = (pointer, pointer, size, pointer, size, pointer, size)
    library.ZSTD_compressSequences.restype = size
    library.ZSTD_isError.argtypes, library.ZSTD_isError.restype = (size,), ct.c_uint
    source = np.frombuffer(raw, dtype=np.uint8)
    before = ct.create_string_buffer(len(raw) * 2)
    ctx = library.ZSTD_createCCtx()
    assert ctx
    try:
        options = [(100, 1), (200, 0), (201, 1)]
        sequence_data = None
        if sequences:
            options.extend(((1008, 1), (1009, 1)))  # Explicit delimiters and sequence validation.
            sequence_data = (ct.c_uint32 * (4 * len(sequences)))(*(x for row in sequences for x in row))
        for key, value in options:
            assert not library.ZSTD_isError(library.ZSTD_CCtx_setParameter(ctx, key, value))
        result = library.ZSTD_compressSequences(ctx, ct.addressof(before), len(before), sequence_data, len(sequences),
                                                source.ctypes.data, len(raw))
        assert not library.ZSTD_isError(result)
        return before.raw[:result]
    finally:
        library.ZSTD_freeCCtx(ctx)


@pytest.fixture(scope="module")
def literal_only():
    random = np.random.default_rng(827118)
    blocks = [random.integers(first, first + 63, size, dtype=np.uint8).tobytes()
              for first, size in zip((0, 64, 0, 0, 128), (131072, 131072, 131072, 131072, 65535), strict=True)]
    raw = b"".join(blocks)
    return with_literals(raw), raw


def test_pair_keeps_both_ordered_tables_and_an_ordinary_singleton(decoder, literal_only):
    frame, raw = literal_only
    receipt = authority(frame, raw)
    planned = pair.plan(frame, len(raw))
    assert len(planned) == 5
    assert planned[0][3] == 1 and planned[1][3] == 1 and planned[3][3] == 0
    native, control = decoder.verified(frame, receipt)
    result, counts = decoder.verified(frame, receipt, paired=True)
    assert (bytes(result), result.readonly) == (bytes(native), True)
    assert bytes(native) == raw
    assert (control["route"], counts["route"]) == ("ordinary", "paired")
    assert counts["pair_count"] == 2 and counts["different_tables"] == counts["singletons"] == 1


def test_unsupported_match_blocks_use_original_decoder(decoder):
    raw = bytes(range(146)) * 2028
    frame = zstd.ZstdCompressor(write_checksum=True).compress(raw)
    actual, counters = decoder.verified(frame, authority(frame, raw), paired=True)
    assert bytes(actual) == raw
    assert counters["route"] == "ordinary_fallback" and not counters["candidate_eligible"]


def test_mixed_seam_uses_contiguous_prior_history_and_registers_its_table(decoder):
    rng = np.random.default_rng(7654)
    blocks = [rng.integers(low, low + 64, 131072, dtype=np.uint8).tobytes() for low in (0, 0, 64, 64, 64)]
    blocks[2] = blocks[1][-20:-16] + blocks[2][4:]
    raw = b"".join(blocks)
    sequences = ((0, 131072, 0, 0), (0, 131072, 0, 0), (20, 0, 4, 0),
                 (0, 131068, 0, 0), (0, 131072, 0, 0), (0, 131072, 0, 0))
    frame = with_literals(raw, sequences)
    planned = pair.plan(frame, len(raw))
    assert planned[2][3] == 1 and planned[2][5] > 0
    assert planned[3][3] == 0
    actual, counts = decoder.verified(frame, authority(frame, raw), paired=True)
    assert bytes(actual) == raw
    assert (counts["mixed_blocks"], counts["pair_count"], counts["singletons"]) == (1, 2, 0)
    assert counts["history_bytes"] >= 20


def test_multiple_mixed_blocks_use_original_decoder(decoder):
    rng = np.random.default_rng(7655)
    blocks = [rng.integers(low, low + 64, 131072, dtype=np.uint8).tobytes() for low in (0, 64, 128)]
    for index in (1, 2):
        blocks[index] = blocks[index-1][-20:-16] + blocks[index][4:]
    raw = b"".join(blocks)
    sequences = ((0, 131072, 0, 0), (20, 0, 4, 0), (0, 131068, 0, 0),
                 (20, 0, 4, 0), (0, 131068, 0, 0))
    frame = with_literals(raw, sequences)
    actual, counts = decoder.verified(frame, authority(frame, raw), paired=True)
    assert bytes(actual) == raw
    assert counts["route"] == "ordinary_fallback" and not counts["candidate_eligible"]


def test_original_complete_encoded_checksum_and_all_decoded_checks_remain(decoder, literal_only):
    frame, raw = literal_only
    receipt = authority(frame, raw)
    broken = frame[:-1] + bytes([frame[-1] ^ 1])
    with pytest.raises(ValueError, match="encoded member"):
        decoder.verified(broken, receipt, paired=True)
    with pytest.raises(ValueError, match="frame, checksum"):
        decoder.verified(broken, replace(receipt, encoded_sha256=pair.digest(broken)), paired=True)
    with pytest.raises(ValueError, match="member digest"):
        decoder.verified(frame, replace(receipt, decoded_sha256=pair.digest(b"")), paired=True)
    with pytest.raises(ValueError, match="window extent or digest"):
        decoder.verified(frame, replace(receipt, windows=((3, pair.digest(b"")),)), paired=True)
    valid = ((3, pair.digest(raw[:3])),)
    with pytest.raises(ValueError, match="ordered window extent"):
        decoder.verified(frame, replace(receipt, windows=valid), paired=True)
